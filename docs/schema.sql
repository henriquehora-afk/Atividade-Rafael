-- =============================================================================
-- SGF — Sistema de Gestão e Fiscalização de Obras
-- Módulo 5: Controle de Ponto e Jornada de Operários
--
-- Esquema relacional normalizado até a 3ª Forma Normal (3FN)
-- Dialeto: PostgreSQL 14+ (SQL padrão, sem extensões)
--
-- Rastreabilidade (V-Model / UML):
--   * DER/MER .................. docs/der-mer-modulo5.png
--   * Diagrama de Sequência .... docs/diagrama-sequencia-registro-ponto.png
--   * Runtime local (SQLite) ... backend/src/db/schemaSqlite.ts (mesmo modelo,
--                                 adaptado ao dialeto SQLite: RAISE(ABORT), strftime)
--
-- Separação 3FN:
--   Cadastros Mestres ............ OBRA, ESCALA_TURNO, COLABORADOR
--   Ocorrência Transacional ...... REGISTO_PONTO (IMUTÁVEL — Portaria MTP 671/2021)
--   Auditoria / Retificação 0:1 .. JUSTIFICATIVA_AJUSTE
--   Dados derivados .............. somente em VIEWS (nenhuma coluna física de totais)
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. OBRA (Cadastro Mestre)
-- -----------------------------------------------------------------------------
CREATE TABLE OBRA (
    id_obra        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    codigo_obra    VARCHAR(50)  NOT NULL,
    nome_canteiro  VARCHAR(150) NOT NULL,
    localidade     VARCHAR(100) NOT NULL,
    CONSTRAINT pk_obra PRIMARY KEY (id_obra),
    CONSTRAINT uk_obra_codigo UNIQUE (codigo_obra)
);

-- -----------------------------------------------------------------------------
-- 2. ESCALA_TURNO (Cadastro Mestre)
--    tolerancia_clt_min: CLT Art. 58 §1º — variações de até 10 min diários
--    não são computadas como hora extra nem descontadas.
-- -----------------------------------------------------------------------------
CREATE TABLE ESCALA_TURNO (
    id_escala                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    descricao_turno           VARCHAR(100) NOT NULL,
    carga_horaria_diaria_min  INTEGER      NOT NULL,
    tolerancia_clt_min        INTEGER      NOT NULL DEFAULT 10,
    CONSTRAINT pk_escala_turno PRIMARY KEY (id_escala),
    CONSTRAINT ck_escala_carga CHECK (carga_horaria_diaria_min > 0 AND carga_horaria_diaria_min <= 720),
    CONSTRAINT ck_escala_tolerancia CHECK (tolerancia_clt_min >= 0 AND tolerancia_clt_min <= 10)
);

-- -----------------------------------------------------------------------------
-- 3. COLABORADOR (Cadastro Mestre)
--    ESCALA_TURNO (1) --define_jornada--> (1:N) COLABORADOR
-- -----------------------------------------------------------------------------
CREATE TABLE COLABORADOR (
    id_colaborador        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_escala             INTEGER      NOT NULL,
    matricula             VARCHAR(30)  NOT NULL,
    nome_completo         VARCHAR(150) NOT NULL,
    funcao                VARCHAR(100) NOT NULL,
    hash_template_facial  VARCHAR(255) NOT NULL,
    CONSTRAINT pk_colaborador PRIMARY KEY (id_colaborador),
    CONSTRAINT uk_colaborador_matricula UNIQUE (matricula),
    CONSTRAINT fk_colaborador_escala FOREIGN KEY (id_escala)
        REFERENCES ESCALA_TURNO (id_escala) ON DELETE RESTRICT
);

-- -----------------------------------------------------------------------------
-- 4. REGISTO_PONTO (Ocorrência Transacional — IMUTÁVEL)
--    OBRA (1) --recebe--> (1:N) REGISTO_PONTO
--    COLABORADOR (1) --realiza--> (0:N) REGISTO_PONTO
--    data_hora_batida = horário ORIGINAL da captura em campo (nunca o do sync).
-- -----------------------------------------------------------------------------
CREATE TABLE REGISTO_PONTO (
    id_registo            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_colaborador        INTEGER      NOT NULL,
    id_obra               INTEGER      NOT NULL,
    data_hora_batida      TIMESTAMP    NOT NULL,
    tipo_batida           VARCHAR(20)  NOT NULL,
    confianca_facial      DECIMAL(5,2) NOT NULL,
    sincronizado_offline  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_registo_ponto PRIMARY KEY (id_registo),
    CONSTRAINT fk_registo_colaborador FOREIGN KEY (id_colaborador)
        REFERENCES COLABORADOR (id_colaborador) ON DELETE RESTRICT,
    CONSTRAINT fk_registo_obra FOREIGN KEY (id_obra)
        REFERENCES OBRA (id_obra) ON DELETE RESTRICT,
    CONSTRAINT ck_registo_tipo_batida
        CHECK (tipo_batida IN ('ENTRADA', 'SAIDA_ALMOCO', 'VOLTA_ALMOCO', 'SAIDA')),
    CONSTRAINT ck_registo_confianca
        CHECK (confianca_facial >= 0 AND confianca_facial <= 100)
);

CREATE INDEX idx_registo_colaborador_data ON REGISTO_PONTO (id_colaborador, data_hora_batida);
CREATE INDEX idx_registo_obra_data        ON REGISTO_PONTO (id_obra, data_hora_batida);

-- -----------------------------------------------------------------------------
-- 5. JUSTIFICATIVA_AJUSTE (Auditoria / Retificação)
--    REGISTO_PONTO (1) --gera_retificacao--> (0:1) JUSTIFICATIVA_AJUSTE
--    A cardinalidade 0:1 é garantida pelo UNIQUE em id_registo.
-- -----------------------------------------------------------------------------
CREATE TABLE JUSTIFICATIVA_AJUSTE (
    id_ajuste           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_registo          INTEGER      NOT NULL,
    motivo_ajuste       TEXT         NOT NULL,
    responsavel_rh      VARCHAR(150) NOT NULL,
    data_hora_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_justificativa_ajuste PRIMARY KEY (id_ajuste),
    CONSTRAINT uk_justificativa_registo UNIQUE (id_registo),
    CONSTRAINT fk_justificativa_registo FOREIGN KEY (id_registo)
        REFERENCES REGISTO_PONTO (id_registo) ON DELETE RESTRICT,
    CONSTRAINT ck_justificativa_motivo CHECK (length(trim(motivo_ajuste)) > 0)
);

-- =============================================================================
-- TRIGGERS DE IMUTABILIDADE — Portaria MTP nº 671/2021
-- Batidas não podem ser alteradas nem excluídas. Retificações ocorrem
-- exclusivamente via INSERT em JUSTIFICATIVA_AJUSTE.
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_registo_ponto_imutavel() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Registro de ponto e imutavel conforme Portaria 671/2021'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_registo_ponto_bloqueia_update
    BEFORE UPDATE ON REGISTO_PONTO
    FOR EACH ROW EXECUTE FUNCTION fn_registo_ponto_imutavel();

CREATE TRIGGER trg_registo_ponto_bloqueia_delete
    BEFORE DELETE ON REGISTO_PONTO
    FOR EACH ROW EXECUTE FUNCTION fn_registo_ponto_imutavel();

CREATE TRIGGER trg_registo_ponto_bloqueia_truncate
    BEFORE TRUNCATE ON REGISTO_PONTO
    FOR EACH STATEMENT EXECUTE FUNCTION fn_registo_ponto_imutavel();

-- A própria trilha de auditoria também é append-only.
CREATE OR REPLACE FUNCTION fn_justificativa_imutavel() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Justificativa de ajuste e imutavel (trilha de auditoria)'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_justificativa_bloqueia_update
    BEFORE UPDATE ON JUSTIFICATIVA_AJUSTE
    FOR EACH ROW EXECUTE FUNCTION fn_justificativa_imutavel();

CREATE TRIGGER trg_justificativa_bloqueia_delete
    BEFORE DELETE ON JUSTIFICATIVA_AJUSTE
    FOR EACH ROW EXECUTE FUNCTION fn_justificativa_imutavel();

-- =============================================================================
-- VIEWS DE DADOS DERIVADOS (sem redundância física)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- vw_espelho_ponto_diario
--   Uma linha por colaborador/dia. Pareia cada batida de "entrada"
--   (ENTRADA, VOLTA_ALMOCO) com a batida seguinte de "saída"
--   (SAIDA_ALMOCO, SAIDA) do mesmo dia e soma os intervalos.
--   Precisão exata: soma em SEGUNDOS inteiros -> MINUTOS inteiros ->
--   CENTÉSIMOS de hora inteiros (arredondamento half-up: (min*100+30)/60)
--   -> DECIMAL(10,2). Nenhum cálculo intermediário usa ponto flutuante.
-- -----------------------------------------------------------------------------
CREATE VIEW vw_espelho_ponto_diario AS
WITH batidas_ordenadas AS (
    SELECT
        r.id_registo,
        r.id_colaborador,
        r.tipo_batida,
        r.data_hora_batida,
        r.sincronizado_offline,
        CAST(r.data_hora_batida AS DATE) AS data_jornada,
        LEAD(r.tipo_batida) OVER (
            PARTITION BY r.id_colaborador, CAST(r.data_hora_batida AS DATE)
            ORDER BY r.data_hora_batida, r.id_registo) AS proximo_tipo,
        LEAD(r.data_hora_batida) OVER (
            PARTITION BY r.id_colaborador, CAST(r.data_hora_batida AS DATE)
            ORDER BY r.data_hora_batida, r.id_registo) AS proxima_hora
    FROM REGISTO_PONTO r
),
intervalos AS (
    SELECT
        b.*,
        CASE
            WHEN b.tipo_batida IN ('ENTRADA', 'VOLTA_ALMOCO')
             AND b.proximo_tipo IN ('SAIDA_ALMOCO', 'SAIDA')
            THEN CAST(EXTRACT(EPOCH FROM (b.proxima_hora - b.data_hora_batida)) AS BIGINT)
            ELSE 0
        END AS segundos_trabalhados
    FROM batidas_ordenadas b
),
agregado AS (
    SELECT
        i.id_colaborador,
        i.data_jornada,
        COUNT(*)                                                         AS total_batidas,
        SUM(CASE WHEN i.sincronizado_offline THEN 1 ELSE 0 END)          AS batidas_offline,
        SUM(CASE WHEN i.tipo_batida IN ('ENTRADA', 'VOLTA_ALMOCO') THEN 1 ELSE 0 END) AS qtd_marcacoes_entrada,
        SUM(CASE WHEN i.tipo_batida IN ('SAIDA_ALMOCO', 'SAIDA') THEN 1 ELSE 0 END)   AS qtd_marcacoes_saida,
        MIN(i.data_hora_batida)                                          AS primeira_batida,
        MAX(i.data_hora_batida)                                          AS ultima_batida,
        MAX(CASE WHEN i.proximo_tipo IS NULL THEN i.tipo_batida END)     AS tipo_ultima_batida,
        SUM(i.segundos_trabalhados) / 60                                 AS minutos_trabalhados,
        COUNT(j.id_ajuste)                                               AS qtd_ajustes
    FROM intervalos i
    LEFT JOIN JUSTIFICATIVA_AJUSTE j ON j.id_registo = i.id_registo
    GROUP BY i.id_colaborador, i.data_jornada
)
SELECT
    a.id_colaborador,
    c.matricula,
    c.nome_completo,
    c.funcao,
    e.id_escala,
    e.descricao_turno,
    e.carga_horaria_diaria_min,
    e.tolerancia_clt_min,
    a.data_jornada,
    a.total_batidas,
    a.batidas_offline,
    a.primeira_batida,
    a.ultima_batida,
    a.tipo_ultima_batida,
    a.minutos_trabalhados,
    (a.minutos_trabalhados * 100 + 30) / 60                                   AS centesimos_trabalhados,
    CAST((a.minutos_trabalhados * 100 + 30) / 60 AS DECIMAL(10,2)) / 100      AS horas_trabalhadas,
    CAST((e.carga_horaria_diaria_min * 100 + 30) / 60 AS DECIMAL(10,2)) / 100 AS carga_horaria_horas,
    a.minutos_trabalhados - e.carga_horaria_diaria_min                        AS saldo_minutos,
    CASE
        WHEN a.tipo_ultima_batida IN ('ENTRADA', 'VOLTA_ALMOCO')
             AND a.data_jornada = CURRENT_DATE                           THEN 'EM_ANDAMENTO'
        WHEN a.qtd_marcacoes_entrada <> a.qtd_marcacoes_saida            THEN 'INCOMPLETA'
        WHEN a.minutos_trabalhados - e.carga_horaria_diaria_min >  e.tolerancia_clt_min THEN 'HORA_EXTRA'
        WHEN e.carga_horaria_diaria_min - a.minutos_trabalhados >  e.tolerancia_clt_min THEN 'DEBITO'
        ELSE 'CONFORME'
    END                                                                        AS situacao_jornada,
    CASE WHEN a.qtd_ajustes > 0 THEN TRUE ELSE FALSE END                       AS possui_ajuste,
    a.qtd_ajustes
FROM agregado a
JOIN COLABORADOR  c ON c.id_colaborador = a.id_colaborador
JOIN ESCALA_TURNO e ON e.id_escala      = c.id_escala;

-- -----------------------------------------------------------------------------
-- vw_resumo_presenca_obra
--   Por obra: colaboradores atualmente presentes (última batida do
--   colaborador, HOJE, é ENTRADA ou VOLTA_ALMOCO e ocorreu nesta obra),
--   batidas do dia, sincronizações offline e ajustes auditados.
-- -----------------------------------------------------------------------------
CREATE VIEW vw_resumo_presenca_obra AS
WITH ultima_batida AS (
    SELECT
        r.id_colaborador,
        r.id_obra,
        r.tipo_batida,
        r.data_hora_batida,
        ROW_NUMBER() OVER (
            PARTITION BY r.id_colaborador
            ORDER BY r.data_hora_batida DESC, r.id_registo DESC) AS ordem
    FROM REGISTO_PONTO r
),
presentes AS (
    SELECT u.id_obra, COUNT(*) AS qtd
    FROM ultima_batida u
    WHERE u.ordem = 1
      AND u.tipo_batida IN ('ENTRADA', 'VOLTA_ALMOCO')
      AND CAST(u.data_hora_batida AS DATE) = CURRENT_DATE
    GROUP BY u.id_obra
),
batidas AS (
    SELECT
        r.id_obra,
        SUM(CASE WHEN CAST(r.data_hora_batida AS DATE) = CURRENT_DATE THEN 1 ELSE 0 END) AS batidas_hoje,
        SUM(CASE WHEN r.sincronizado_offline
                  AND CAST(r.data_hora_batida AS DATE) = CURRENT_DATE THEN 1 ELSE 0 END) AS sincronizados_offline_hoje,
        SUM(CASE WHEN r.sincronizado_offline THEN 1 ELSE 0 END)                         AS total_sincronizado_offline,
        COUNT(*)                                                                         AS total_batidas
    FROM REGISTO_PONTO r
    GROUP BY r.id_obra
),
ajustes AS (
    SELECT r.id_obra, COUNT(j.id_ajuste) AS qtd
    FROM JUSTIFICATIVA_AJUSTE j
    JOIN REGISTO_PONTO r ON r.id_registo = j.id_registo
    GROUP BY r.id_obra
)
SELECT
    o.id_obra,
    o.codigo_obra,
    o.nome_canteiro,
    o.localidade,
    COALESCE(p.qtd, 0)                         AS colaboradores_presentes,
    COALESCE(b.batidas_hoje, 0)                AS batidas_hoje,
    COALESCE(b.sincronizados_offline_hoje, 0)  AS sincronizados_offline_hoje,
    COALESCE(b.total_sincronizado_offline, 0)  AS total_sincronizado_offline,
    COALESCE(b.total_batidas, 0)               AS total_batidas,
    COALESCE(aj.qtd, 0)                        AS total_ajustes_auditados
FROM OBRA o
LEFT JOIN presentes p  ON p.id_obra  = o.id_obra
LEFT JOIN batidas   b  ON b.id_obra  = o.id_obra
LEFT JOIN ajustes   aj ON aj.id_obra = o.id_obra;

